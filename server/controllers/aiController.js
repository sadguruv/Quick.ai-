import { generateImageFromText } from "../utils/aiProviders.js";
import fs from "fs";
import * as localDb from "../db/localDb.js";
import { exec } from "child_process";
import path from "path";
import { fileURLToPath } from 'url';
import axios from "axios";
import { ValidationError } from "../middlewares/errorHandler.js";

export const removeImageBackground = async (req, res) => {
  const userId = req.userId || 'guest';
  let tempInputPath = null;
  let isTempCreated = false;

  try {
    const currentCredits = localDb.getCredits(userId);
    if (currentCredits < 10) {
      return res.status(400).json({
        success: false,
        message: "Insufficient credits. Required: 10, Available: " + currentCredits
      });
    }

    let inputPath = null;

    // 1. Direct file upload via Multer
    if (req.file && req.file.path) {
      inputPath = req.file.path;
    }
    // 2. Body Payload (URL or Base64 from created/generated image)
    else {
      const rawImage = req.body.imageUrl || req.body.imageBase64 || req.body.image;
      if (!rawImage) {
        throw new ValidationError("Image file or Image URL/Data is required");
      }

      const uploadsDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'uploads');
      if (!fs.existsSync(uploadsDir)) {
        fs.mkdirSync(uploadsDir, { recursive: true });
      }

      tempInputPath = path.join(uploadsDir, `bg_in_${Date.now()}_${Math.random().toString(36).substring(7)}.png`);
      isTempCreated = true;

      // Handle Remote HTTP / HTTPS URL
      if (typeof rawImage === 'string' && (rawImage.startsWith('http://') || rawImage.startsWith('https://'))) {
        const response = await axios.get(rawImage, { responseType: 'arraybuffer', timeout: 20000 });
        fs.writeFileSync(tempInputPath, Buffer.from(response.data));
      }
      // Handle Base64 Data URI or Base64 string
      else if (typeof rawImage === 'string') {
        const base64Data = rawImage.replace(/^data:image\/\w+;base64,/, '');
        fs.writeFileSync(tempInputPath, Buffer.from(base64Data, 'base64'));
      }

      inputPath = tempInputPath;
    }

    if (!inputPath || !fs.existsSync(inputPath)) {
      throw new ValidationError("Valid image could not be prepared for background removal");
    }

    const outputPath = `${inputPath}_removed.png`;
    const __dirname = path.dirname(fileURLToPath(import.meta.url));
    const scriptPath = path.resolve(__dirname, '..', 'bg_remove_service.py');

    console.log(`[Rembg CLI] Starting background removal on ${inputPath}...`);

    const venvPython = path.resolve(__dirname, '..', '..', 'rembg', 'venv', 'Scripts', 'python.exe');
    const pythonExe = fs.existsSync(venvPython) ? `"${venvPython}"` : 'python';
    const command = `${pythonExe} "${scriptPath}" "${inputPath}" "${outputPath}"`;

    await new Promise((resolve, reject) => {
      exec(command, (error, stdout, stderr) => {
        if (error) {
          console.error("Rembg CLI Error:", stderr || error.message);
          reject(new Error(stderr || error.message));
        } else {
          console.log("Rembg CLI Output:", stdout);
          resolve(stdout);
        }
      });
    });

    if (fs.existsSync(outputPath)) {
      const fileBuffer = fs.readFileSync(outputPath);
      const content = `data:image/png;base64,${fileBuffer.toString("base64")}`;

      // Cleanup
      try {
        if (fs.existsSync(inputPath)) fs.unlinkSync(inputPath);
        if (fs.existsSync(outputPath)) fs.unlinkSync(outputPath);
      } catch (e) {}

      const newCredits = localDb.deductCredit(userId, 10);
      localDb.saveCreation({
        userId,
        prompt: "Background Removal",
        content,
        type: "image"
      });

      return res.status(200).json({ success: true, data: { content, credits: newCredits } });
    } else {
      throw new Error("Output file was not generated by Rembg Python script");
    }

  } catch (error) {
    console.error("Background Removal Controller Error:", error.message);

    // Safe Cleanup
    try {
      if (tempInputPath && fs.existsSync(tempInputPath)) fs.unlinkSync(tempInputPath);
    } catch (e) {}

    if (!res.headersSent) {
      return res.status(500).json({
        success: false,
        message: error.message || "Background Removal Failed"
      });
    }
  }
};

export const generateImage = async (req, res) => {
  try {
    const { prompt } = req.body;
    if (!prompt || prompt.trim() === "") {
      return res.status(400).json({ success: false, message: "Prompt is required" });
    }

    const userId = req.userId;
    const currentCredits = localDb.getCredits(userId);
    if (currentCredits < 10) {
      return res.status(400).json({ success: false, message: "Insufficient credits. Required: 10, Available: " + currentCredits });
    }

    const content = await generateImageFromText(prompt);
    const newCredits = localDb.deductCredit(userId, 10);
    localDb.saveCreation({
      userId,
      prompt,
      content,
      type: "image"
    });

    return res.status(200).json({ success: true, data: { content, credits: newCredits } });

  } catch (error) {
    console.error("[Image Gen Error]:", error.message);
    if (!res.headersSent) {
      return res.status(500).json({ success: false, message: error.message || "Image Generation Failed" });
    }
  }
};
