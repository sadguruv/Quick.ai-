
import { generateImageService } from "../services/stableDiffusionService.js";
import * as localDb from "../db/localDb.js";

/**
 * Controller for Stable Diffusion Image Generation.
 * Handles the HTTP request/response cycle.
 */
export const generateImageController = async (req, res, next) => {
    try {
        const { prompt } = req.body;

        if (!prompt || typeof prompt !== "string" || prompt.trim().length === 0) {
            return res.status(400).json({ error: "Prompt is required and must be a non-empty string." });
        }

        const userId = req.userId;
        const currentCredits = localDb.getCredits(userId);
        if (currentCredits < 10) {
            return res.status(400).json({ error: "Insufficient credits. Required: 10, Available: " + currentCredits });
        }

        console.log(`[SD Controller] Received prompt: ${prompt.substring(0, 50)}...`);

        const base64Image = await generateImageService(prompt);

        // Construct the data URL
        const imageContent = `data:image/png;base64,${base64Image}`;

        const newCredits = localDb.deductCredit(userId, 10);
        localDb.saveCreation({
            userId,
            prompt,
            content: imageContent,
            type: "image"
        });

        // Return standard JSON response
        res.status(200).json({
            success: true,
            data: {
                content: imageContent,
                credits: newCredits,
                note: "Generated by Stable Diffusion (Local)"
            }
        });

    } catch (error) {
        console.error("[SD Controller] Error:", error.message);
        res.status(500).json({
            success: false,
            error: error.message || "Failed to generate image."
        });
    }
};
